import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {makeCatalog,verifyCatalog} from './release-catalog.mjs';
const repo='fage-go/magicnotice',tag='signed-aaaa000';
const a=(lang,id=lang==='zh'?777:778)=>{const name='cicada_'+lang+'_release_v1680-signed.apk';return {id,size:42,name,state:'uploaded',browser_download_url:'https://github.com/'+repo+'/releases/download/'+tag+'/'+name}};
const row={tag_name:tag,published_at:'2026-11-18T06:00:00Z',name:'Official build',draft:false,prerelease:true,assets:[a('en'),a('zh')]};
const d=makeCatalog(repo,'magicnotice-signed',[row]);
assert(d && d.downloads.length===2 && d.downloads[0].id===777);
assert.equal(d.downloads[0].downloadUrl,'https://download.hifage.com/v2/assets/'+repo+'/'+tag+'/777');
assert.equal(d.downloads[0].originalUrl,a('zh').browser_download_url);
assert(verifyCatalog(repo,'magicnotice-signed',d));
assert.equal(verifyCatalog(repo,'magicnotice-signed',{...d,repo:'bad/repo'}),null);
for(const key of ['originalUrl','downloadUrl'])assert.equal(verifyCatalog(repo,'magicnotice-signed',{...d,downloads:[...d.downloads.slice(0,1),{...d.downloads[1],[key]:'https://other.invalid/pkg'}]}),null);
assert.equal(makeCatalog(repo,'magicnotice-signed',[{...row,assets:[a('zh')]}]),null);
assert.equal(makeCatalog(repo,'magicnotice-signed',[{...row,draft:true}]),null);
const w='fage-go/other',up='https://github.com/'+w+'/releases/download/v1%2Fbeta/pkg.zip';
const other=makeCatalog(w,'uploaded',[{...row,tag_name:'v1/beta',assets:[{id:123,size:13,name:'pkg.zip',state:'uploaded',browser_download_url:up}]}]);
assert.equal(other.downloads[0].downloadUrl,'https://download.hifage.com/v2/assets/'+w+'/v1%2Fbeta/123');
const seed=JSON.parse(readFileSync(new URL('../public/release-catalog/fage-go/magicnotice.json',import.meta.url),'utf8'));
assert(verifyCatalog(repo,'magicnotice-signed',seed));
console.log('PASS release catalog seed, generic asset metadata, exact relay and original URL, release completeness');
